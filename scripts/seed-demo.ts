import { mkdir, writeFile } from "node:fs/promises";
import { createClient } from "@supabase/supabase-js";
import { createDemoData } from "../src/lib/seed";
import { recordSchemas, tables, toDatabase, type MutableCollection } from "../src/lib/supabase/validation";

async function main() {
  const demo = createDemoData();
  if (!process.argv.includes("--apply-local")) {
    await mkdir("artifacts",{recursive:true});
    await writeFile("artifacts/demo-workspace.json",JSON.stringify(demo,null,2));
    console.log("Generated fictional fixtures: artifacts/demo-workspace.json. No database was changed.");
    console.log("To seed a dedicated local Supabase, set DEMO_EMAIL/DEMO_PASSWORD and run npm run db:seed-demo -- --apply-local.");
    return;
  }
  const url=process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key=process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  const email=process.env.DEMO_EMAIL;
  const password=process.env.DEMO_PASSWORD;
  if (!url || !key || !email || !password) throw new Error("Set local Supabase URL/public key and DEMO_EMAIL/DEMO_PASSWORD. No service-role key is used.");
  if (!["localhost","127.0.0.1","[::1]"].includes(new URL(url).hostname)) throw new Error("Demo seeding is restricted to a dedicated localhost Supabase. Remote databases are never seeded by this script.");
  const supabase=createClient(url,key,{auth:{persistSession:false,autoRefreshToken:false}});
  const signIn=await supabase.auth.signInWithPassword({email,password});
  if (signIn.error || !signIn.data.user) throw new Error("Sign in failed. Create and confirm a dedicated local demo user first.");
  const userId=signIn.data.user.id;
  const existing=await supabase.from("accounts").select("id").eq("user_id",userId).limit(1);
  if (existing.error) throw new Error("Apply the finance migration before seeding.");
  if (existing.data.length) throw new Error("This owner already has accounts. Demo seeding only accepts an empty dedicated demo workspace.");
  const collections:MutableCollection[]=["accounts","transactions","snapshots","bills","fixedDeposits","loans","emis","groups","shares","settlements","reminders","allocations","emiAllocations"];
  for (const collection of collections) {
    for (const value of demo[collection]) {
      const record=recordSchemas[collection].parse({...value,userId});
      const result=collection==="allocations" ? await supabase.rpc("allocate_bill_payment",{p_id:record.id,p_bill_id:(record as {billId:string}).billId,p_transaction_id:(record as {transactionId:string}).transactionId,p_amount:(record as {amount:string}).amount,p_verified:(record as {verified:boolean}).verified}) : collection==="emiAllocations" ? await supabase.rpc("allocate_emi_payment",{p_id:record.id,p_emi_id:(record as {emiId:string}).emiId,p_transaction_id:(record as {transactionId:string}).transactionId,p_amount:(record as {amount:string}).amount}) : await supabase.from(tables[collection]).insert(toDatabase(record,userId));
      if (result.error) throw new Error(`Local demo seeding stopped at ${collection}. Database message: ${result.error.code}. Reset the dedicated local database before retrying.`);
    }
  }
  await supabase.auth.signOut();
  console.log("Fictional fixtures inserted into the dedicated local demo owner's workspace. Audits were generated by PostgreSQL.");
}
main().catch(error=>{console.error(error instanceof Error ? error.message : "Demo seed failed.");process.exitCode=1;});
